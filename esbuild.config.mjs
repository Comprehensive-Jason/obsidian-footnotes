import esbuild from "esbuild";
import process from "node:process";
import { readFile } from "node:fs/promises";
import { builtinModules } from "node:module";

// `npm run dev` (watch mode) keeps a readable build with inline sourcemaps;
// `npm run build` type-checks first (tsc -noEmit), then minifies for release
const prod = process.argv[2] === "production";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
https://github.com/Comprehensive-Jason/obsidian-footnotes
Includes third-party code under the MIT License; notices are in LICENSE-THIRD-PARTY.md in that repository.
*/
`;

// The build stops if main.js holds a call of eval, since a plugin review or a
// scanner may flag one. The "format" package bundled inside remark-obsidian
// used to carry an eval fallback that could never run here; the build rewrote
// it away until remark-obsidian 2.2.0 removed it upstream (2026-11-09). This
// check stays so a later upgrade can't bring one back unnoticed.
// Any call of eval, written plainly as "eval(" or the indirect way the minifier
// writes that line, "(0,eval)(". A property merely named eval, like the one in
// the "fault" package, is no call, so it does not count.
const EvalCall = /\beval\s*\)?\s*\(/;

const context = await esbuild.context({
    banner: { js: banner },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: [
        "obsidian",
        "electron",
        "@codemirror/autocomplete",
        "@codemirror/collab",
        "@codemirror/commands",
        "@codemirror/language",
        "@codemirror/lint",
        "@codemirror/search",
        "@codemirror/state",
        "@codemirror/view",
        "@lezer/common",
        "@lezer/highlight",
        "@lezer/lr",
        ...builtinModules,
        ...builtinModules.map((m) => `node:${m}`),
    ],
    format: "cjs",
    // es2018, matching the official sample plugin: Android WebViews can lag
    // years behind (degoogled phones, e-ink readers — see issue #46), and
    // untranspiled ?. / ?? syntax makes the whole plugin fail to LOAD there
    target: "es2018",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    outfile: "main.js",
    minify: prod,
});

if (prod) {
    await context.rebuild();
    await context.dispose();
    const built = await readFile("main.js", "utf8");
    const call = EvalCall.exec(built);
    if (call !== null) {
        console.error(`main.js holds a call of eval, a plugin review or a scanner may flag it: ...${built.slice(Math.max(0, call.index - 60), call.index + 40)}...`);
        process.exit(1);
    }
} else {
    await context.watch();
}
